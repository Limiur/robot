# 有限时域 LQR（Finite-Horizon Linear Quadratic Regulator）问题
#
# 目标：在有限时间区间 [0, N] 内，求一组最优控制输入 u_0, u_1, ..., u_{N-1}，
# 使得系统状态演化满足：
#     x_{k+1} = A x_k + B u_k
# 其中：
#     x_k ∈ R^n       状态
#     u_k ∈ R^m       控制输入
#     A ∈ R^{n×n}    状态矩阵
#     B ∈ R^{n×m}    控制矩阵
#
# 代价函数（离散时间有限时域 LQR）：
#     J = Σ_{k=0}^{N-1} (x_k^T Q x_k + u_k^T R u_k) + x_N^T Q_f x_N
# 其中：
#     Q ≥ 0          状态加权矩阵
#     R > 0          控制加权矩阵
#     Q_f ≥ 0        终端状态加权矩阵
#
# 结论：最优控制为状态反馈形式：
#     u_k = -K_k x_k
# 其中反馈增益 K_k 由 Riccati 方程反向求解得到。
#
# 离散时间 Riccati 方程（反向递推）：
#     P_N = Q_f
#     P_k = Q + A^T P_{k+1} A
#           - A^T P_{k+1} B (R + B^T P_{k+1} B)^{-1} B^T P_{k+1} A
#     K_k = (R + B^T P_{k+1} B)^{-1} B^T P_{k+1} A
#
# 物理含义：
#   - 从终端时刻 N 开始倒推，逐步计算每一时刻的最优价值函数矩阵 P_k
#   - 然后得到每个时刻的反馈增益 K_k
#   - 最终可得到闭环控制律 u_k = -K_k x_k
#
# 典型求解流程：
#   1. 给定系统矩阵 A、B，以及代价矩阵 Q、R、Q_f
#   2. 令 P_N = Q_f
#   3. 对 k = N-1, N-2, ..., 0 反向递推计算 P_k 和 K_k
#   4. 生成闭环控制器 u_k = -K_k x_k
#   5. 根据初始状态 x_0 进行系统仿真，得到最优轨迹
#
# 代码结构（通常是这样的）：
#   - 读取系统参数 A, B, Q, R, Q_f
#   - 调用 Riccati 反向迭代计算 P 和 K
#   - 进行状态仿真与控制计算
#   - 可视化或输出状态轨迹与控制序列
#
# 注意：
#   - 这里的 R 通常要求正定，保证控制代价可逆且问题有唯一最优解
#   - 若系统不稳定或参数设计不合理，需额外考虑可控性和可观测性条件
#   - 若需要处理带约束的 LQR，可进一步引入约束优化或 MPC
#
# 这是一个有限时域 LQR 问题的基本理论框架与求解思路。
# 实际计算时可使用 NumPy / SciPy 完成矩阵运算与 Riccati 迭代。
#
# 例子：
#   x_{k+1} = A x_k + B u_k
